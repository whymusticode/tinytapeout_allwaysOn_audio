"""Generate RTL constants from the golden model, so the two cannot drift apart.

  python model/gen_rtl.py      # writes src/filterbank_coeffs.vh

The filterbank coefficients for every band count the Stage A search can pick
(search_space.FRONTEND["bands"]), at the chip's widths (frontend_var.LEAN5); src/filterbank.v
selects one table with its N_BANDS parameter, so changing the band count is a parameter change.
"""

from pathlib import Path

import frontend_var as FV

ROOT = Path(__file__).resolve().parent.parent
BAND_COUNTS = [8, 10, 12, 14, 16, 20, 24]


def filterbank_coeffs_vh():
    cw = FV.LEAN5["coef_frac"] + 2
    lines = [
        "// Generated by model/gen_rtl.py from frontend_var.coeffs_int(). Do not edit.",
        f"// Q2.{FV.LEAN5['coef_frac']} band-pass resonator coefficients ({cw} bits), mel-spaced, for each",
        "// band count; term 0: g, term 1: -a1, term 2: -a2 (negated so every term is added).",
        "// Included inside module filterbank: N_BANDS picks the table.",
        f"function automatic signed [{cw - 1}:0] fb_coef(input [4:0] band, input [1:0] term);",
        "  begin",
        f"    fb_coef = {cw}'sd0;",
        "    case (N_BANDS)",
    ]
    for nb in BAND_COUNTS:
        v = FV.variant(**FV.LEAN5, bands=nb, order=4)
        g, a1, a2 = FV.coeffs_int(v)
        fc = FV.band_centers(v)
        lines += [f"      {nb}:  // centers " + ", ".join(f"{f:.0f}" for f in fc) + " Hz",
                  "        case ({band, term})"]
        for b in range(nb):
            for t, c in enumerate((g[b], -a1[b], -a2[b])):
                c = int(c)
                assert -(1 << (cw - 1)) <= c < (1 << (cw - 1)), (nb, b, t, c)
                lit = f"{cw}'sd{c}" if c >= 0 else f"-{cw}'sd{-c}"
                lines.append(f"          {{5'd{b}, 2'd{t}}}: fb_coef = {lit};")
        lines += ["          default: ;", "        endcase"]
    lines += ["      default: ;", "    endcase", "  end", "endfunction", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    (ROOT / "src" / "filterbank_coeffs.vh").write_text(filterbank_coeffs_vh())
    print("wrote src/filterbank_coeffs.vh")
