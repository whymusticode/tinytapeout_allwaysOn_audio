 * Mel filterbank -> log2 frame energies (the Stage A front end).
 *
 * Per PCM sample, for each band b (one shared bit-serial multiplier, BPC coefficient bits per
 * clock):
 *   x    = pcm >> (16 - PCM_BITS)                           (LSBs dropped)
 *   v    = (x[n] - x[n-2]) << (16 - PCM_BITS + GUARD)
 *   y    = sat(g*v + (-a1)*y1 + (-a2)*y2 + 2^(COEF_FRAC-1)) >> COEF_FRAC)
 * ORDER = 4 runs the same resonator again on w = y - y2 (y2 before this sample's update):
 *   z    = sat(g*w + (-a1)*z1 + (-a2)*z2 + 2^(COEF_FRAC-1)) >> COEF_FRAC)
 *   e[b] = sat(e[b] + (|z or y| >> ACC_SHIFT))
 * Every 2^HOP_LOG2 samples each band's log2 code ({msb position, next LOG_FRAC bits}) is clipped
 * to FEAT_BITS above FEAT_LO and output on feat/feat_band with feat_valid (one band per clock,
 * band 0 first), and e[] is cleared.
 *
 * Coefficients: filterbank_coeffs.vh (generated by model/gen_rtl.py) holds a table per band
 * count; N_BANDS picks one.
 *
 * Timing: each section is 3 products x COEF_W / BPC clocks, then one clock to saturate; the
 * |y| and energy updates get a clock each, so no clock does more than one adder's work
 * (ASIC_VERIFY.md). Clocks per sample = N_BANDS x (ORDER 4: 2 x (3 x COEF_W/BPC + 2) + 3;
 * ORDER 2: 3 x COEF_W/BPC + 4) + 1, plus N_BANDS clocks per frame for the output: 24 bands,
 * order 4, BPC 2, 10-bit coefficients = 889 + 24 of the 1024 clocks per sample at 16.384 MHz.
 * pcm_valid must not arrive while `busy`.
 *
 * Bit-exact reference: model/frontend_var.py:_fb_one() (+ code_range clipping), with the chip's
 * widths in frontend_var.LEAN5; test/unit/test_filterbank.py.
 */

`default_nettype none

module filterbank #(
    parameter N_BANDS   = 12,
    parameter ORDER     = 4,   // 2 or 4
    parameter BPC       = 2,   // coefficient bits per clock; COEF_W % BPC == 0
    parameter HOP_LOG2  = 8,   // 256-sample frames (16 ms)
    parameter PCM_BITS  = 12,
    parameter COEF_W    = 10,
    parameter COEF_FRAC = 8,
    parameter Y_W       = 18,
    parameter GUARD     = 4,
    parameter ACC_W     = 20,
    parameter ACC_SHIFT = 4,
    parameter LOG_FRAC  = 2,
    parameter FEAT_BITS = 6
) (
    input  wire                 clk,
    input  wire                 rst_n,
    input  wire [         15:0] pcm,
    input  wire                 pcm_valid,
    output reg  [FEAT_BITS-1:0] feat,
    output reg  [          4:0] feat_band,
    output reg                  feat_valid,
    output wire                 busy
);

  `include "filterbank_coeffs.vh"

  localparam V_W = PCM_BITS + 1 + (16 - PCM_BITS) + GUARD;  // (x[n] - x[n-2]) << ...
  localparam D_W = (V_W > Y_W + 1) ? V_W : Y_W + 1;          // widest data operand
  localparam P_W = COEF_W + D_W + 2;                         // sum of three products + rounding
  localparam CHUNKS = COEF_W / BPC;
  localparam CODE_W = 5 + LOG_FRAC;
  // frontend_var.code_range: keep 2^FEAT_BITS levels from log2 energy 7 up (or the whole range)
  localparam TOP = ACC_W << LOG_FRAC;
  localparam LEVELS = 1 << FEAT_BITS;
  localparam FEAT_LO = (LEVELS >= TOP) ? 0 : ((7 << LOG_FRAC) < TOP - LEVELS ? (7 << LOG_FRAC) : TOP - LEVELS);
  localparam integer LAST_BAND = N_BANDS - 1;

  localparam [2:0] S_IDLE = 3'd0, S_LOAD = 3'd1, S_MAC = 3'd2, S_SAT = 3'd3, S_W = 3'd4,
                   S_ABS = 3'd5, S_ACC = 3'd6, S_OUT = 3'd7;
  reg [2:0] state;
  assign busy = state != S_IDLE;

  // Per-band state in rotating shift registers: index 0 is the current band.
  reg signed [Y_W-1:0] y1 [0:N_BANDS-1];
  reg signed [Y_W-1:0] y2 [0:N_BANDS-1];
  reg signed [Y_W-1:0] z1 [0:N_BANDS-1];
  reg signed [Y_W-1:0] z2 [0:N_BANDS-1];
  reg [ACC_W-1:0] e [0:N_BANDS-1];

  reg signed [PCM_BITS-1:0] xm1, xm2;
  reg signed [V_W-1:0] v;
  reg [HOP_LOG2-1:0] n_in_frame;

  reg [4:0] band;
  reg [2:0] term;   // 0..2: g*v, -a1*y1, -a2*y2; 3..5: g*w, -a1*z1, -a2*z2
  reg [4:0] chunk;
  reg signed [P_W-1:0] acc;   // the current section's sum
  reg signed [P_W-1:0] dsh;   // data operand << (chunk * BPC)
  reg [COEF_W-1:0] csh;       // coefficient >> (chunk * BPC)
  reg signed [Y_W-1:0] ysec, zq;  // section outputs y, z
  reg signed [Y_W:0] w;           // y - y2, input of the second section
  reg [Y_W-ACC_SHIFT-1:0] mag;    // |output| >> ACC_SHIFT

  function automatic [1:0] cidx(input [2:0] t);  // the second section reuses g, -a1, -a2
    case (t)
      3'd3:    cidx = 2'd0;
      3'd4:    cidx = 2'd1;
      3'd5:    cidx = 2'd2;
      default: cidx = t[1:0];
    endcase
  endfunction

  function automatic signed [P_W-1:0] operand(input [2:0] t);
    case (t)
      3'd0:    operand = {{(P_W - V_W) {v[V_W-1]}}, v};
      3'd1:    operand = {{(P_W - Y_W) {y1[0][Y_W-1]}}, y1[0]};
      3'd2:    operand = {{(P_W - Y_W) {y2[0][Y_W-1]}}, y2[0]};
      3'd3:    operand = {{(P_W - Y_W - 1) {w[Y_W]}}, w};
      3'd4:    operand = {{(P_W - Y_W) {z1[0][Y_W-1]}}, z1[0]};
      default: operand = {{(P_W - Y_W) {z2[0][Y_W-1]}}, z2[0]};
    endcase
  endfunction

  // BPC coefficient bits per clock; the coefficient's top bit has weight -2^(COEF_W-1).
  reg signed [P_W-1:0] acc_next;
  integer k;
  always @(*) begin
    acc_next = acc;
    for (k = 0; k < BPC; k = k + 1)
      if (csh[k]) begin
        if (chunk == CHUNKS - 1 && k == BPC - 1) acc_next = acc_next - (dsh <<< k);
        else acc_next = acc_next + (dsh <<< k);
      end
  end

  wire signed [P_W-1:0] acc_sh = acc >>> COEF_FRAC;
  wire signed [P_W-COEF_FRAC-1:0] s_sh = acc_sh[P_W-COEF_FRAC-1:0];
  localparam signed [P_W-COEF_FRAC-1:0] Y_MAX = (1 <<< (Y_W - 1)) - 1;
  localparam signed [P_W-COEF_FRAC-1:0] Y_MIN = -(1 <<< (Y_W - 1));
  wire signed [Y_W-1:0] q = (s_sh > Y_MAX) ? Y_MAX[Y_W-1:0] : (s_sh < Y_MIN) ? Y_MIN[Y_W-1:0] : s_sh[Y_W-1:0];

  wire signed [Y_W-1:0] y_out = (ORDER == 4) ? zq : ysec;
  wire [Y_W-1:0] y_abs = y_out[Y_W-1] ? -y_out : y_out;  // |Y_MIN| fits as unsigned
  wire [ACC_W:0] e_sum = {1'b0, e[0]} + {{(ACC_W + 1 - (Y_W - ACC_SHIFT)) {1'b0}}, mag};
  wire [ACC_W-1:0] e_new = e_sum[ACC_W] ? {ACC_W{1'b1}} : e_sum[ACC_W-1:0];

  wire signed [PCM_BITS-1:0] xs = pcm[15:16-PCM_BITS];
  wire signed [PCM_BITS:0] dx = $signed({xs[PCM_BITS-1], xs}) - $signed({xm2[PCM_BITS-1], xm2});

  // log2 code of e[0]: msb position p, next LOG_FRAC bits; then clipped to the feature range.
  wire [ACC_W-1:0] e_out = e[0];
  reg [4:0] p;
  integer j;
  always @(*) begin
    p = 0;
    for (j = 0; j < ACC_W; j = j + 1) if (e_out[j]) p = j[4:0];
  end
  wire [ACC_W+LOG_FRAC-1:0] e_norm = {e_out, {LOG_FRAC{1'b0}}} >> p;
  wire [CODE_W-1:0] code = (e_out == 0) ? {CODE_W{1'b0}} : {p, e_norm[LOG_FRAC-1:0]};
  wire [CODE_W-1:0] code_lo = code - FEAT_LO[CODE_W-1:0];
  wire [FEAT_BITS-1:0] feat_code = (code < FEAT_LO) ? {FEAT_BITS{1'b0}} :
                                   (code_lo >= LEVELS) ? {FEAT_BITS{1'b1}} : code_lo[FEAT_BITS-1:0];

  localparam signed [P_W-1:0] RND = 1 <<< (COEF_FRAC - 1);

  wire _unused = &{1'b0, pcm[15-PCM_BITS:0], y_abs[ACC_SHIFT-1:0], e_norm[ACC_W+LOG_FRAC-1:LOG_FRAC], acc_sh[P_W-1:P_W-COEF_FRAC]};

  integer i;
  always @(posedge clk) begin
    if (!rst_n) begin
      state      <= S_IDLE;
      xm1        <= 0;
      xm2        <= 0;
      v          <= 0;
      n_in_frame <= 0;
      band       <= 0;
      term       <= 0;
      chunk      <= 0;
      acc        <= 0;
      dsh        <= 0;
      csh        <= 0;
      ysec       <= 0;
      zq         <= 0;
      w          <= 0;
      mag        <= 0;
      feat       <= 0;
      feat_band  <= 0;
      feat_valid <= 0;
      for (i = 0; i < N_BANDS; i = i + 1) begin
        y1[i] <= 0;
        y2[i] <= 0;
        z1[i] <= 0;
        z2[i] <= 0;
        e[i]  <= 0;
      end
    end else begin
      feat_valid <= 0;
      case (state)
        S_IDLE:
        if (pcm_valid) begin
          v     <= {dx, {(16 - PCM_BITS + GUARD) {1'b0}}};
          xm2   <= xm1;
          xm1   <= xs;
          band  <= 0;
          term  <= 0;
          state <= S_LOAD;
        end

        S_LOAD: begin  // start a section: first operand, rounding constant
          csh   <= fb_coef(band, cidx(term));
          dsh   <= operand(term);
          chunk <= 0;
          acc   <= RND;
          state <= S_MAC;
        end

        S_MAC: begin
          acc   <= acc_next;
          dsh   <= dsh <<< BPC;
          csh   <= csh >> BPC;
          chunk <= chunk + 1'b1;
          if (chunk == CHUNKS - 1) begin
            if (term == 3'd2 || term == 3'd5) begin
              state <= S_SAT;
            end else begin  // next product of the same section, no gap
              term  <= term + 1'b1;
              csh   <= fb_coef(band, cidx(term + 1'b1));
              dsh   <= operand(term + 1'b1);
              chunk <= 0;
            end
          end
        end

        S_SAT: begin
          if (term == 3'd2) begin
            ysec  <= q;
            state <= (ORDER == 4) ? S_W : S_ABS;
          end else begin
            zq    <= q;
            state <= S_ABS;
          end
        end

        S_W: begin  // second section input: y - y2 (y2 not yet updated)
          w     <= $signed({ysec[Y_W-1], ysec}) - $signed({y2[0][Y_W-1], y2[0]});
          term  <= 3'd3;
          state <= S_LOAD;
        end

        S_ABS: begin
          mag   <= y_abs[Y_W-1:ACC_SHIFT];
          state <= S_ACC;
        end

        S_ACC: begin  // energy, then rotate to the next band
          for (i = 0; i < N_BANDS - 1; i = i + 1) begin
            y1[i] <= y1[i+1];
            y2[i] <= y2[i+1];
            z1[i] <= z1[i+1];
            z2[i] <= z2[i+1];
            e[i]  <= e[i+1];
          end
          y1[N_BANDS-1] <= ysec;
          y2[N_BANDS-1] <= y1[0];
          z1[N_BANDS-1] <= (ORDER == 4) ? zq : {Y_W{1'b0}};
          z2[N_BANDS-1] <= (ORDER == 4) ? z1[0] : {Y_W{1'b0}};
          e[N_BANDS-1]  <= e_new;
          term          <= 0;
          if (band == LAST_BAND[4:0]) begin
            band       <= 0;
            n_in_frame <= n_in_frame + 1'b1;
            state      <= (&n_in_frame) ? S_OUT : S_IDLE;
          end else begin
            band  <= band + 1'b1;
            state <= S_LOAD;
          end
        end

        S_OUT: begin
          feat       <= feat_code;
          feat_band  <= band;
          feat_valid <= 1;
          for (i = 0; i < N_BANDS - 1; i = i + 1) e[i] <= e[i+1];
          e[N_BANDS-1] <= 0;
          band <= band + 1'b1;
          if (band == LAST_BAND[4:0]) begin
            band  <= 0;
            state <= S_IDLE;
          end
        end

        default: state <= S_IDLE;
      endcase
    end
  end

endmodule
